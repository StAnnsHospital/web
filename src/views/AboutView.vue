// Augment window for optional libs
interface GsapLike {
  registerPlugin: (plugin: unknown) => void
  from: (targets: unknown, vars: Record<string, unknown>) => void
}
interface WindowWithLibs extends Window {
  gsap?: GsapLike
  ScrollTrigger?: unknown
  SplitType?: new (el: HTMLElement, opts: Record<string, unknown>) => { chars: HTMLElement[] }
}

interface RevealEl extends HTMLElement {
  _revealedSplit?: unknown
  _basicSplit?: boolean
}

onMounted(() => {
  const w = window as WindowWithLibs

  const initGsapTextReveal = () => {
    if (!w.gsap || !w.ScrollTrigger || !w.SplitType) return false
    const gsap = w.gsap
    gsap.registerPlugin(w.ScrollTrigger)
  const els = document.querySelectorAll<RevealEl>('.text-reveal-anim')
    if (!els.length) return true
    els.forEach(el => {
      // Avoid double-processing
      if (el._revealedSplit) return
      const SplitType = w.SplitType!
      const split = new SplitType(el, { types: 'chars' })
      el._revealedSplit = split
      gsap.from(split.chars, {
        scrollTrigger: {
          trigger: el,
          start: 'top 80%',
          end: 'top 30%',
          scrub: true,
          once: true
        },
        opacity: 0,
        yPercent: 25,
        stagger: 0.04,
        duration: 0.6,
        ease: 'power3.out'
      })
    })
    return true
  }

  // Retry until libraries loaded (e.g., external script tags) then init
  let attempts = 0
  const maxAttempts = 40 // ~2s @ 50ms
  const interval = setInterval(() => {
    attempts++
    if (initGsapTextReveal() || attempts >= maxAttempts) {
      clearInterval(interval)
      // Fallback if GSAP never loaded
      if (attempts >= maxAttempts) {
        setupFallbackReveal()
      }
    }
  }, 50)

  // Fallback: basic fade/slide in using IntersectionObserver
  function setupFallbackReveal() {
  const targets = document.querySelectorAll<RevealEl>('.text-reveal-anim')
    if (!targets.length) return
    const observer = new IntersectionObserver(entries => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          const el = entry.target as RevealEl
          if (!el._basicSplit) {
            basicSplit(el)
          }
          el.querySelectorAll<HTMLElement>('[data-char]').forEach((span, i) => {
            span.style.transition = 'opacity .5s ease, transform .5s ease'
            span.style.transitionDelay = (i * 40) + 'ms'
            requestAnimationFrame(() => {
              span.style.opacity = '1'
              span.style.transform = 'translateY(0)'
            })
          })
          observer.unobserve(el)
        }
      })
    }, { rootMargin: '0px 0px -20% 0px' })
    targets.forEach(t => observer.observe(t))
  }

  function basicSplit(el: RevealEl) {
    const text = el.innerHTML
    // Skip if contains tags; for simplicity only split plain text sections
    const hasTag = /<[^>]+>/.test(text)
    if (hasTag) return
    const chars = text.split('').map(ch => `<span data-char style="display:inline-block;opacity:0;transform:translateY(25%);">${ch === ' ' ? '&nbsp;' : ch}</span>`).join('')
    el.innerHTML = chars
  el._basicSplit = true
  }
})
